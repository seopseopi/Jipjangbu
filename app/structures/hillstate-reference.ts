const scale = 12.57 / 349;
const xy = (x: number, y: number): Point => [
  (x - 126) * scale,
  (400 - y) * scale,
];
const polygon = (points: Point[]) => points.map(([x, y]) => xy(x, y));
const room = (
  id: string,
  name: string,
  points: Point[],
  label: Point,
): Room => ({ id, name, polygon: polygon(points), label: xy(...label) });
const wall = (
  id: string,
  start: Point,
  end: Point,
  exterior = false,
): Wall => ({
  id,
  start: xy(...start),
  end: xy(...end),
  thickness: exterior ? 0.18 : 0.12,
  height: 2.4,
});
const door = (
  id: string,
  wallId: string,
  offset: number,
  width: number,
  hinge: "start" | "end" = "start",
  opensTo: "left" | "right" = "left",
): Opening => ({
  id,
  wallId,
  offset: offset * scale,
  width: width * scale,
  height: 2.05,
  hinge,
  opensTo,
});
const windowOpening = (
  id: string,
  wallId: string,
  offset: number,
  width: number,
): Opening => ({
  id,
  wallId,
  offset: offset * scale,
  width: width * scale,
  height: 1.3,
  sillHeight: 0.7,
});
